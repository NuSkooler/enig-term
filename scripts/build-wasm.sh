#!/usr/bin/env bash
# Build the WASM modules: cargo -> wasm-bindgen (web target) -> wasm-opt -Oz.
#
#   build/wasm/         enig-term-core   (the emulation engine; always loaded)
#   build/wasm-zmodem/  enig-term-zmodem (ZModem; loaded for a transfer)
#
# Needs: rustup toolchain with wasm32-unknown-unknown, wasm-bindgen-cli 0.2.129
# (must match the wasm-bindgen crate version in both Cargo.toml files), and
# optionally binaryen's wasm-opt. Override tool paths with WASM_BINDGEN /
# WASM_OPT. CARGO_TOOLCHAIN defaults to "stable".
#
# cargo runs with --locked: the committed Cargo.lock files are what gets built,
# and a build that would change one fails instead. While changing dependencies,
# run `cargo update` (or `cargo generate-lockfile`) in the crate and commit the
# lock, or build once with CARGO_LOCKED=0. CI and release builds keep it on.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TOOLCHAIN="${CARGO_TOOLCHAIN:-stable}"
FEATURES="${CORE_FEATURES:-}"
WASM_BINDGEN="${WASM_BINDGEN:-wasm-bindgen}"
WASM_OPT="${WASM_OPT:-wasm-opt}"
LOCKED=--locked
if [ "${CARGO_LOCKED:-1}" = "0" ]; then LOCKED=; fi

"$ROOT/scripts/prepare-icy.sh"

# build <crate dir> <crate file stem> <out dir> [cargo features]
build() {
    local crate="$1" stem="$2" out="$3" features="${4:-}"
    (cd "$crate" && cargo "+$TOOLCHAIN" build ${LOCKED:+"$LOCKED"} --release --target wasm32-unknown-unknown ${features:+--features "$features"})
    local raw="${CARGO_TARGET_DIR:-$crate/target}/wasm32-unknown-unknown/release/$stem.wasm"

    rm -rf "$out" && mkdir -p "$out"
    "$WASM_BINDGEN" --target web --out-dir "$out" "$raw"

    # Panic recovery: a wasm32 panic is a trap that leaves the instance unusable
    # (stack pointer and RefCell borrow flags are not restored). The shell then
    # instantiates the module again, which wasm-bindgen's init refuses once it
    # has run. These exports let it start over. The glue is generated by the
    # pinned wasm-bindgen 0.2.129, whose module-level `wasm` binding this relies on.
    local glue="$out/$stem.js"
    grep -q '^let wasmModule, wasmInstance, wasm;$' "$glue" || { echo "build-wasm: unexpected wasm-bindgen glue layout" >&2; exit 1; }
    cat >> "$glue" <<'JS'

/** enig-term: forget the current instance so init can create a fresh one. */
export function __enigReset() {
    wasm = undefined;
    wasmInstance = undefined;
}
/** enig-term: the compiled module of the current instance, for re-instantiation. */
export function __enigModule() {
    return wasmModule;
}
JS
    cat >> "$out/$stem.d.ts" <<'TS'
export function __enigReset(): void;
export function __enigModule(): WebAssembly.Module | undefined;
TS

    if command -v "$WASM_OPT" >/dev/null 2>&1; then
        "$WASM_OPT" -Oz --enable-bulk-memory --enable-nontrapping-float-to-int --enable-sign-ext \
            --enable-mutable-globals --enable-reference-types --enable-multivalue \
            "$out/${stem}_bg.wasm" -o "$out/${stem}_bg.opt.wasm"
        mv "$out/${stem}_bg.opt.wasm" "$out/${stem}_bg.wasm"
    else
        echo "warning: wasm-opt not found; $stem is not size-optimised" >&2
    fi

    local r o g
    r=$(stat -c %s "$raw")
    o=$(stat -c %s "$out/${stem}_bg.wasm")
    g=$(gzip -9 -c "$out/${stem}_bg.wasm" | wc -c)
    echo "$stem: cargo ${r} B, bindgen+wasm-opt ${o} B, gzip -9 ${g} B"
}

build "$ROOT/crates/enig-term-core" enig_term_core "$ROOT/build/wasm" "$FEATURES"
build "$ROOT/crates/enig-term-zmodem" enig_term_zmodem "$ROOT/build/wasm-zmodem"
