#!/usr/bin/env python3
"""Generate crates/enig-term-core/src/delegate.rs: trait impls for CaptureScreen
that forward every method TextScreen implements to the inner TextScreen.

Run after each icy_tools rebase:  python3 scripts/gen-delegate.py <icy_tools checkout>
Methods listed in OVERRIDDEN are skipped here and written by hand in capture.rs
(they must run on the wrapper so its scroll capture and link tracking see them).
"""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1]) / 'crates/icy_engine/src/text_buffer/text_screen.rs'
out = pathlib.Path(__file__).resolve().parent.parent / 'crates/enig-term-core/src/delegate.rs'
OVERRIDDEN = {'scroll_up', 'scroll_down', 'clear_screen', 'print_char', 'set_char',
              'as_editable', 'as_any_mut', 'clear_scrollback', 'scroll_left', 'scroll_right'}

text = src.read_text().splitlines()
blocks, cur = {}, None
for line in text:
    m = re.match(r'^impl (\w+) for TextScreen', line)
    if m:
        cur = m.group(1); blocks[cur] = []; continue
    if line.startswith('}'):
        cur = None; continue
    if cur and line.startswith('    fn '):
        sig = line.strip().rstrip('{').strip()
        name = re.match(r'fn (\w+)', sig).group(1)
        if name in OVERRIDDEN:
            continue
        args = re.search(r'\((.*)\)', sig.split('->')[0]).group(1)
        names = []
        for a in [x.strip() for x in args.split(',')][1:]:
            if not a: continue
            n = a.split(':')[0].replace('mut ', '').strip()
            names.append(n)
        sig = sig.replace('mut sixel', 'sixel').replace('crate::', 'icy_engine::')
        blocks[cur].append(f'    {sig} {{\n        self.inner.{name}({", ".join(names)})\n    }}\n')

hdr = '''// @generated by scripts/gen-delegate.py from icy_engine's text_screen.rs.
// Forwards every TextScreen trait method to the wrapped screen, except the
// ones capture.rs implements itself. Do not edit by hand: regenerate.
#![allow(clippy::all)]
use std::sync::Arc;


use icy_engine::{
    AttributedChar, BitFont, Caret, EditableScreen, HyperLink, IceMode, Layer, Line, MouseField, Palette, Position, Rectangle, RenderOptions, Result,
    SaveOptions, SavedCaretState, Screen, Selection, Sixel, Size, TerminalState, TextPane,
};
use icy_parser_core::{RipCommand, SkypixCommand};
use parking_lot::Mutex;

use crate::capture::CaptureScreen;
'''
body = [hdr]
for trait in ('TextPane', 'Screen', 'EditableScreen'):
    if trait == 'TextPane':
        body.append(f'\nimpl {trait} for CaptureScreen {{\n')
    elif trait == 'Screen':
        body.append(f'\nimpl {trait} for CaptureScreen {{\n')
        body.append('    fn as_editable(&mut self) -> Option<&mut dyn EditableScreen> {\n        Some(self)\n    }\n\n')
        body.append('    fn as_any_mut(&mut self) -> &mut dyn std::any::Any {\n        self\n    }\n\n')
    else:
        body.append(f'\nimpl {trait} for CaptureScreen {{\n')
        body.append('    crate::icy_capture_overrides!();\n\n')
    body.append('\n'.join(blocks[trait]))
    body.append('}\n')
out.write_text(''.join(body))
print(f'wrote {out}')
