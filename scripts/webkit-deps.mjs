// WebKit for the Playwright tests on hosts that lack some of its system
// libraries, without root.
//
// Playwright's WebKit build (WPE MiniBrowser) links against system libraries
// that a desktop may not have (on Ubuntu 24.04: libevent-2.1-7t64 and libavif16).
// `npx playwright install-deps webkit` installs them system-wide with sudo.
// This script is the no-root alternative: it downloads the .debs with
// `apt-get download`, unpacks them into ~/.cache/enig-term/wkdeps, and writes a
// launcher that adds them to LD_LIBRARY_PATH. playwright.config.ts then picks
// the launcher up by itself.
//
//   node scripts/webkit-deps.mjs          check, and fetch what is missing
//   node scripts/webkit-deps.mjs --check  only report
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const CACHE = path.join(process.env.XDG_CACHE_HOME ?? path.join(os.homedir(), '.cache'), 'enig-term', 'wkdeps');
const LAUNCHER = path.join(CACHE, 'webkit-run.sh');

/** Missing sonames we know how to supply, with the Debian/Ubuntu packages that hold them (and their own deps). */
const PACKAGES = {
    'libevent-2.1.so.7': ['libevent-2.1-7t64', 'libevent-2.1-7'],
    'libavif.so.16': ['libavif16', 'libgav1-1', 'libyuv0'],
};

function browsersPath() {
    return process.env.PLAYWRIGHT_BROWSERS_PATH && process.env.PLAYWRIGHT_BROWSERS_PATH !== '0'
        ? process.env.PLAYWRIGHT_BROWSERS_PATH
        : path.join(os.homedir(), process.platform === 'darwin' ? 'Library/Caches/ms-playwright' : '.cache/ms-playwright');
}

/** The WPE MiniBrowser directory of the newest installed Playwright WebKit, or null. */
export function findWpe() {
    const base = browsersPath();
    let dirs = [];
    try {
        dirs = fs.readdirSync(base).filter(d => /^webkit-\d+$/.test(d));
    } catch {
        return null;
    }
    dirs.sort((a, b) => Number(b.split('-')[1]) - Number(a.split('-')[1]));
    for (const d of dirs) {
        const wpe = path.join(base, d, 'minibrowser-wpe');
        if (fs.existsSync(path.join(wpe, 'bin', 'MiniBrowser'))) return wpe;
    }
    return null;
}

/** Sonames that the dynamic loader cannot find for WebKit, given extra library dirs. */
export function missingLibs(wpe, extraLibDirs = []) {
    const libDirs = [path.join(wpe, 'lib'), path.join(wpe, 'sys', 'lib'), ...extraLibDirs];
    const targets = [path.join(wpe, 'bin', 'MiniBrowser'), path.join(wpe, 'bin', 'WPEWebProcess'), path.join(wpe, 'bin', 'WPENetworkProcess')];
    for (const f of fs.readdirSync(path.join(wpe, 'lib'))) if (/^libWPE.*\.so/.test(f) || /^libwpe.*\.so/.test(f)) targets.push(path.join(wpe, 'lib', f));
    const missing = new Set();
    for (const t of targets) {
        if (!fs.existsSync(t)) continue;
        let out = '';
        try {
            out = execFileSync('ldd', [t], { env: { ...process.env, LD_LIBRARY_PATH: libDirs.join(':') }, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
        } catch (e) {
            out = String(e.stdout ?? '');
        }
        for (const m of out.matchAll(/^\s*(\S+) => not found/gm)) missing.add(m[1]);
    }
    return [...missing];
}

function cacheLibDir() {
    return path.join(CACHE, 'root', 'usr', 'lib', `${os.arch() === 'arm64' ? 'aarch64' : 'x86_64'}-linux-gnu`);
}

function writeLauncher(wpe) {
    const sh = `#!/bin/sh
# Generated by enig-term scripts/webkit-deps.mjs: Playwright's WPE MiniBrowser
# with libraries unpacked from .debs (no root). Same environment as its own
# MiniBrowser wrapper, plus the extra library directory.
MYDIR=${JSON.stringify(wpe)}
export WEBKIT_EXEC_PATH="\${MYDIR}/bin"
export WEBKIT_INJECTED_BUNDLE_PATH="\${MYDIR}/lib"
export WEBKIT_INSPECTOR_RESOURCES_PATH="\${MYDIR}/share"
export LD_LIBRARY_PATH="\${MYDIR}/lib:\${MYDIR}/sys/lib:${cacheLibDir()}"
exec "\${MYDIR}/bin/MiniBrowser" "$@"
`;
    fs.mkdirSync(CACHE, { recursive: true });
    fs.writeFileSync(LAUNCHER, sh, { mode: 0o755 });
}

/**
 * How Playwright should launch WebKit here:
 *   { ok: true }                      the installed build runs as is
 *   { ok: true, executablePath }      it runs through our launcher
 *   { ok: false, reason }             it cannot run; skip it
 * WEBKIT_EXECUTABLE, if set, always wins.
 */
export function webkitLaunch() {
    if (process.env.WEBKIT_EXECUTABLE) return { ok: true, executablePath: process.env.WEBKIT_EXECUTABLE };
    if (process.platform !== 'linux') return { ok: true };
    const wpe = findWpe();
    if (!wpe) return { ok: false, reason: 'Playwright WebKit is not installed (npx playwright install webkit)' };
    let missing;
    try {
        missing = missingLibs(wpe);
    } catch {
        return { ok: true }; // no ldd: let Playwright try
    }
    if (!missing.length) return { ok: true };
    if (fs.existsSync(LAUNCHER) && !missingLibs(wpe, [cacheLibDir()]).length) return { ok: true, executablePath: LAUNCHER };
    return {
        ok: false,
        reason: `WebKit needs system libraries this host lacks (${missing.join(', ')}). Run "npm run setup:webkit" (no root) or "npx playwright install-deps webkit" (root).`,
    };
}

function fetchDebs(wpe, missing) {
    const want = new Set();
    const unknown = [];
    for (const lib of missing) {
        if (PACKAGES[lib]) PACKAGES[lib].forEach(p => want.add(p));
        else unknown.push(lib);
    }
    if (unknown.length) console.warn(`webkit-deps: no package known for ${unknown.join(', ')}; try "npx playwright install-deps webkit"`);
    if (!want.size) return false;
    const debs = path.join(CACHE, 'debs');
    fs.mkdirSync(debs, { recursive: true });
    for (const pkg of want) {
        try {
            execFileSync('apt-get', ['download', pkg], { cwd: debs, stdio: ['ignore', 'inherit', 'pipe'] });
            console.log(`webkit-deps: downloaded ${pkg}`);
        } catch {
            // Alternatives (t64 renames) are listed together; a miss is fine if another one lands.
            console.log(`webkit-deps: ${pkg} not available here, skipped`);
        }
    }
    const root = path.join(CACHE, 'root');
    fs.mkdirSync(root, { recursive: true });
    for (const f of fs.readdirSync(debs).filter(f => f.endsWith('.deb'))) execFileSync('dpkg-deb', ['-x', path.join(debs, f), root]);
    writeLauncher(wpe);
    return true;
}

/**
 * Run as a command, not on import (playwright.config.ts imports this). Real
 * paths on both sides: Node runs a symlinked script from its real path.
 */
function isMain() {
    try {
        return fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url));
    } catch {
        return false; // no argv[1] (node -e, the REPL)
    }
}

if (isMain()) {
    const check = process.argv.includes('--check');
    const wpe = findWpe();
    if (!wpe) {
        console.error('webkit-deps: Playwright WebKit is not installed; run: npx playwright install webkit');
        process.exit(1);
    }
    const missing = missingLibs(wpe);
    if (!missing.length) {
        console.log('webkit-deps: WebKit has every library it needs; nothing to do');
        process.exit(0);
    }
    console.log(`webkit-deps: missing ${missing.join(', ')}`);
    if (check) process.exit(1);
    fetchDebs(wpe, missing);
    const still = missingLibs(wpe, [cacheLibDir()]);
    if (still.length) {
        console.error(`webkit-deps: still missing ${still.join(', ')}`);
        process.exit(1);
    }
    console.log(`webkit-deps: ready; Playwright will use ${LAUNCHER}`);
}
